const ALL = { ...OUTLINE, ...FILLED };

/** icon("clock") → an <svg> string. `cls` lands on the element. */
export function icon(name, cls = "") {
  const body = ALL[name];
  if (!body) {
    // a Basil doodle, drawn at icon size and icon weight
    if (!DOODLES[name]) return "";
    return `<svg class="ico ico--doodle${cls ? " " + cls : ""}" viewBox="0 0 48 48" width="24" height="24" fill="none" stroke="currentColor" `
      + `stroke-width="3.3" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">${DOODLES[name]}</svg>`;
  }
  return `<svg class="ico${cls ? " " + cls : ""}" viewBox="0 0 24 24" width="24" height="24" fill="none" stroke="currentColor" `
    + `stroke-width="1.7" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">${body}</svg>`;
}

export const hasIcon = (name) => Boolean(ALL[name] || DOODLES[name]);
