def mark_rgba(height, color=GREEN, grow=0):
    """The traced mark rasterised from the mask at the requested height."""
    m = mark_mask()
    ys, xs = np.nonzero(m)
    m = m[ys.min():ys.max() + 1, xs.min():xs.max() + 1]
    if grow:
        m = cv2.dilate(m, np.ones((grow, grow), np.uint8))
    a = Image.fromarray(m)
    w = round(a.width * height / a.height)
    a = a.resize((w, height), Image.LANCZOS)
    solid = Image.new("RGBA", a.size, color + (255,))
    solid.putalpha(a)
    return solid


def disc(size, frac, square=False, grow=0):
    bg = Image.new("RGBA", (size * 4, size * 4), (0, 0, 0, 0))
    dr = ImageDraw.Draw(bg)
    if square:
        dr.rectangle((0, 0, size * 4, size * 4), fill=AQUA + (255,))
    else:
        dr.ellipse((0, 0, size * 4 - 1, size * 4 - 1), fill=AQUA + (255,))
    bg = bg.resize((size, size), Image.LANCZOS)
    m = mark_rgba(round(size * frac), grow=grow)
    bg.alpha_composite(m, ((size - m.width) // 2 + round(size * .012), (size - m.height) // 2))
    return bg


def icons():
    out = ROOT / "assets" / "icons"
    out.mkdir(parents=True, exist_ok=True)
    # a home-screen icon is already masked by the OS: full-bleed aqua, the hand inside
    for name, size, frac in (("icon-512", 512, .64), ("icon-192", 192, .64), ("apple-touch-icon", 180, .62)):
        disc(size, frac, square=True).convert("RGB").save(out / f"{name}.png", optimize=True)
    disc(512, .5, square=True).convert("RGB").save(out / "maskable-512.png", optimize=True)
    disc(32, .78, grow=9).save(out / "favicon-32.png", optimize=True)

    og = Image.new("RGB", (1200, 630), AQUA)
    for i, key in enumerate(("pizza-ham", "pepperoni")):
        ph = Image.open(ROOT / "assets" / "photos" / f"{key}.webp").convert("RGB")
        s = 630 / ph.height
        ph = ph.resize((round(ph.width * s), 630), Image.LANCZOS)
        cx = max(0, (ph.width - 330) // 2)
        og.paste(ph.crop((cx, 0, cx + 330, 630)), (540 + i * 330, 0))
    m = mark_rgba(400)
    og.paste(m, ((540 - m.width) // 2, (630 - m.height) // 2 - 20), m)
    og.save(ROOT / "assets" / "og.jpg", "JPEG", quality=86, optimize=True, progressive=True)
    print("  icons 512 / 192 / 180 / maskable / favicon, og.jpg 1200×630")


