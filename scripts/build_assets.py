def photos():
    out = ROOT / "assets" / "photos"
    out.mkdir(parents=True, exist_ok=True)
    for f in out.glob("*.webp"):
        f.unlink()
    src = Image.open(GRID_SHOT).convert("RGB")
    meta, crops = {}, []
    for key, box, _ in PHOTOS:
        im = src.crop(box)
        cw, ch = im.size
        # a thumbnail from a phone screenshot: lift it 2x once, gently, so a
        # retina screen draws real resampled pixels rather than its own blur
        up = im.resize((cw * 2, ch * 2), Image.LANCZOS).filter(ImageFilter.UnsharpMask(radius=1.4, percent=55, threshold=2))
        big, small = up.width, min(360, up.width)
        for suffix, tw, q in (("", big, 84), ("-sm", small, 80)):
            th = round(up.height * tw / up.width)
            frame = up.resize((tw, th), Image.LANCZOS) if tw != up.width else up
            frame.save(out / f"{key}{suffix}.webp", "WEBP", quality=q, method=6)
        r, g, b = im.resize((1, 1), Image.BOX).getpixel((0, 0))
        tone = "#%02x%02x%02x" % (int(r * .85), int(g * .85), int(b * .85))
        meta[key] = {"w": big, "h": up.height, "sw": small, "tone": tone}
        crops.append((key, up))
        print(f"  photo {key:14} {cw}x{ch} → {big}/{small}  tone {tone}")
    (ROOT / "js" / "photos.js").write_text(
        "// GENERATED by scripts/build_assets.py — every photograph's real size and average tone.\n"
        "// w/h: the large file; sw: the small one. The tone paints the frame until the image has pixels.\n"
        "export const PHOTOS = " + json.dumps(meta, indent=2) + ";\n", encoding="utf-8")

    SHOTS.mkdir(parents=True, exist_ok=True)
    th, pad = 230, 10
    cells = [(k, im.resize((round(im.width * th / im.height), th), Image.LANCZOS)) for k, im in crops]
    width = sum(c[1].width + pad for c in cells) + pad
    sheet = Image.new("RGB", (width, th + 40), (245, 250, 251))
    draw = ImageDraw.Draw(sheet)
    x = pad
    for key, im in cells:
        sheet.paste(im, (x, pad))
        draw.text((x + 2, th + 16), key, fill=(2, 89, 61))
        x += im.width + pad
    sheet.save(SHOTS / "crops.jpg", quality=85)


# --------------------------------------------------------------------- logo
EPS = 1.4
MIN_SEP = 1.5
CHAIKIN = 3
SCALE = 3
BOX = (180, 660, 960, 1740)   # the mark inside the avatar screenshot


def chaikin(p, passes=CHAIKIN):
    p = np.asarray(p, float)
    for _ in range(passes):
        q = np.roll(p, -1, axis=0)
        out = np.empty((len(p) * 2, 2))
        out[0::2] = p * .75 + q * .25
        out[1::2] = p * .25 + q * .75
        p = out
    return p


def rdp_open(p, eps):
    keep = np.zeros(len(p), bool)
    keep[0] = keep[-1] = True
    stack = [(0, len(p) - 1)]
    while stack:
        i, j = stack.pop()
        if j <= i + 1:
            continue
        a, b = p[i], p[j]
        seg = p[i + 1:j]
        d = b - a
        n = float(np.hypot(d[0], d[1]))
        if n < 1e-9:
            dist = np.hypot(seg[:, 0] - a[0], seg[:, 1] - a[1])
        else:
            dist = np.abs(d[0] * (seg[:, 1] - a[1]) - d[1] * (seg[:, 0] - a[0])) / n
        k = int(np.argmax(dist))
        if dist[k] > eps:
            m = i + 1 + k
            keep[m] = True
            stack += [(i, m), (m, j)]
    return p[keep]


def rdp_closed(p, eps):
    far = int(np.argmax(np.hypot(p[:, 0] - p[0, 0], p[:, 1] - p[0, 1])))
    a = rdp_open(p[:far + 1], eps)
    b = rdp_open(np.vstack([p[far:], p[:1]]), eps)
    return np.vstack([a[:-1], b[:-1]])


def dedupe(p, minsep):
    out = []
    for x, y in p:
        if not out or (x - out[-1][0]) ** 2 + (y - out[-1][1]) ** 2 >= minsep ** 2:
            out.append((float(x), float(y)))
    while len(out) > 3 and (out[0][0] - out[-1][0]) ** 2 + (out[0][1] - out[-1][1]) ** 2 < minsep ** 2:
        out.pop()
    return out


def smooth_path(ring, scale, ox, oy, prec=1):
    p = [((x - ox) * scale, (y - oy) * scale) for x, y in ring]
    n = len(p)
    f = lambda v: (f"{v:.{prec}f}".rstrip("0").rstrip(".")) or "0"
    dist = lambda a, b: max(((a[0] - b[0]) ** 2 + (a[1] - b[1]) ** 2) ** 0.25, 1e-6)
    d = [f"M{f(p[0][0])} {f(p[0][1])}"]
    for i in range(n):
        p0, p1, p2, p3 = p[(i - 1) % n], p[i], p[(i + 1) % n], p[(i + 2) % n]
        d1, d2, d3 = dist(p1, p0), dist(p2, p1), dist(p3, p2)
        c1 = tuple((d1 * d1 * p2[k] - d2 * d2 * p0[k] + (2 * d1 * d1 + 3 * d1 * d2 + d2 * d2) * p1[k])
                   / (3 * d1 * (d1 + d2)) for k in (0, 1))
        c2 = tuple((d3 * d3 * p1[k] - d2 * d2 * p3[k] + (2 * d3 * d3 + 3 * d3 * d2 + d2 * d2) * p2[k])
                   / (3 * d3 * (d3 + d2)) for k in (0, 1))
        d.append(f"C{f(c1[0])} {f(c1[1])} {f(c2[0])} {f(c2[1])} {f(p2[0])} {f(p2[1])}")
    return "".join(d) + "Z"


def mark_mask():
    """1 where the ink is. Greenness = how much nearer a pixel is to their green
    than to their aqua, a soft 0..255 field that resamples cleanly."""
    im = np.asarray(Image.open(LOGO_SHOT).convert("RGB").crop(BOX)).astype(float)
    dg = np.linalg.norm(im - np.array(GREEN), axis=2)
    da = np.linalg.norm(im - np.array(AQUA), axis=2)
    soft = np.clip(da / (dg + da + 1e-6), 0, 1) * 255
    soft = Image.fromarray(soft.astype(np.uint8)).filter(ImageFilter.GaussianBlur(0.8))
    big = soft.resize((soft.width * SCALE, soft.height * SCALE), Image.BICUBIC)
    mask = (np.asarray(big) > 128).astype(np.uint8) * 255
    n, labels, stats, _ = cv2.connectedComponentsWithStats(mask, 8)
    keep = np.zeros_like(mask)
    for i in range(1, n):
        if stats[i, cv2.CC_STAT_AREA] >= 4000:
            keep[labels == i] = 255
    # close pinholes in the strokes the JPEG left
    keep = cv2.morphologyEx(keep, cv2.MORPH_CLOSE, np.ones((5, 5), np.uint8))
    return keep


def logo():
    mask = mark_mask()
    contours, hier = cv2.findContours(mask, cv2.RETR_CCOMP, cv2.CHAIN_APPROX_NONE)
    ys, xs = np.nonzero(mask)
    x0, x1, y0, y1 = int(xs.min()), int(xs.max()) + 1, int(ys.min()), int(ys.max()) + 1
    scale = 1000.0 / (x1 - x0)
    vh = round((y1 - y0) * scale, 1)
    rings, areas = [], []
    for c in contours:
        pts = c.reshape(-1, 2).astype(float)
        if len(pts) < 60 or cv2.contourArea(c) < 600:
            continue
        rings.append(dedupe(rdp_closed(chaikin(pts), EPS), MIN_SEP))
        areas.append(cv2.contourArea(c))
    d = "".join(smooth_path(r, scale, x0, y0) for r in rings)
    # the three snap strokes are the three smallest rings; the hand is the rest.
    # Split, so the opening screen can snap them in one at a time.
    order = sorted(range(len(rings)), key=lambda i: areas[i])
    snap_ids = sorted(order[:3], key=lambda i: min(p[0] for p in rings[i]))
    body_d = "".join(smooth_path(rings[i], scale, x0, y0) for i in range(len(rings)) if i not in snap_ids)
    snap_ds = [smooth_path(rings[i], scale, x0, y0) for i in snap_ids]

    canvas = np.zeros_like(mask)
    # even-odd, the way the SVG fills it
    for r in rings:
        layer = np.zeros_like(mask)
        cv2.fillPoly(layer, [np.round(np.array(r)).astype(np.int32)], 255)
        canvas = np.bitwise_xor(canvas, layer)
    a, b = canvas > 0, mask > 0
    iou = float((a & b).sum() / (a | b).sum())
    if iou < 0.975:
        raise SystemExit(f"trace disagrees with the source (IoU {iou:.4f})")

    brand = ROOT / "assets" / "brand"
    brand.mkdir(parents=True, exist_ok=True)
    for f in brand.glob("cocona*"):
        f.unlink()
    g = "#%02X%02X%02X" % GREEN
    aq = "#%02X%02X%02X" % AQUA
    (brand / "basil-mark.svg").write_text(
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1000 {vh}" role="img" aria-label="Basil">'
        f'<path fill="{g}" fill-rule="evenodd" d="{d}"/></svg>\n', encoding="utf-8")
    # in their avatar the hand stands about 0.68 of the disc tall
    side = 1500
    s = round(0.68 * side / vh, 4)
    tx, ty = round((side - 1000 * s) / 2 + 20, 1), round((side - vh * s) / 2, 1)
    disc_g = f'transform="translate({tx} {ty}) scale({s})"'
    (brand / "basil-disc.svg").write_text(
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {side} {side}" role="img" aria-label="Basil">'
        f'<circle cx="{side / 2}" cy="{side / 2}" r="{side / 2}" fill="{aq}"/>'
        f'<path {disc_g} fill="{g}" fill-rule="evenodd" d="{d}"/></svg>\n',
        encoding="utf-8")
    js = f"""// GENERATED by scripts/build_assets.py from their avatar — do not edit.
// The pinched fingers, the basil leaf and the three snap strokes, traced to
// curves (IoU {iou:.4f} against the source).

export const MARK_VIEWBOX = "0 0 1000 {vh}";
export const MARK_D = "{d}";
/** The hand and leaf alone, and the three snap strokes left to right. */
export const MARK_BODY = "{body_d}";
export const MARK_SNAPS = {json.dumps(snap_ds)};

/**
 * Their mark.
 *   tone "ink"   currentColor — on paper, in the bars, wherever it takes the text colour
 *   tone "disc"  their avatar: the green hand on the aqua disc
 */
export const DISC_TRANSFORM = '{disc_g}';

export function mark({{ tone = "ink", cls = "", label = "Basil", snap = false }} = {{}}) {{
  const a11y = label ? `role="img" aria-label="${{label}}"` : 'aria-hidden="true"';
  const klass = `mark${{cls ? " " + cls : ""}}`;
  if (snap) {{
    // the strokes as separate paths, so CSS can snap them in one by one
    return `<svg class="${{klass}} mark--snap" viewBox="${{MARK_VIEWBOX}}" ${{a11y}} focusable="false"><path fill="currentColor" d="${{MARK_BODY}}" fill-rule="evenodd"/>`
      + MARK_SNAPS.map((d, i) => `<path class="snap s${{i + 1}}" fill="currentColor" d="${{d}}"/>`).join("") + `</svg>`;
  }}
  if (tone === "disc") {{
    return `<svg class="${{klass}} mark--disc" viewBox="0 0 1500 1500" ${{a11y}} focusable="false"><circle cx="750" cy="750" r="750" fill="var(--aqua)"/><path {disc_g} fill="var(--basil)" fill-rule="evenodd" d="${{MARK_D}}"/></svg>`;
  }}
  return `<svg class="${{klass}}" viewBox="${{MARK_VIEWBOX}}" ${{a11y}} focusable="false"><path fill="currentColor" fill-rule="evenodd" d="${{MARK_D}}"/></svg>`;
}}
"""
    (ROOT / "js" / "brand.js").write_text(js, encoding="utf-8")
    pts = sum(len(r) for r in rings)
    print(f"  logo  {len(rings)} rings, {pts} points, IoU {iou:.4f}, path {len(d) / 1024:.1f} KB, viewBox 1000×{vh}")
    preview = Image.fromarray(np.dstack([canvas, mask, mask]))
    SHOTS.mkdir(parents=True, exist_ok=True)
    preview.save(SHOTS / "trace.png")


