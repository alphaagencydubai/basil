#!/usr/bin/env python3
"""Everything Basil supplied, turned into what the app ships.

The sources are two phone screenshots Ilya sent (src/): their profile picture
opened full screen, and their Instagram profile with the top of the grid.

  logo    the pinched-fingers hand with a basil leaf and three "snap" strokes,
          green on aqua, traced to curves. The mask is the per-pixel distance to
          their green against their aqua, lifted to 3x before thresholding so the
          JPEG blocks do not become bumps; walked with OpenCV, rounded with
          Chaikin, simplified with Douglas-Peucker and written as centripetal
          Catmull-Rom cubics. Held against the source; below IoU .975 the script
          refuses to write it.
  photos  six frames from the top of their grid — two pizzas, the self-order
          kiosk, the tray of square pizza, a guest with a kraft bowl, focaccia
          slices. Each is a 390-pixel thumbnail of the real post, so every crop
          stays clear of Instagram's own reel badge and of the sticker they put
          on their posts, and nothing is drawn larger than twice its pixels.
  icons   their own avatar: the green hand on their aqua disc.
  og      the card a shared link unfolds into.

    python3 scripts/build_assets.py                 # everything
    python3 scripts/build_assets.py photos logo     # just those
"""
